function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function applyTerms(text: string, locale: AdminLocale) {
  const source = locale === "zh-CN" ? TERMS_ZH : TERMS_MY;
  const targetIndex = indexForLocale(locale);
  let output = text;
  for (const phrase of [...source].sort((a, b) => b[0].length - a[0].length)) {
    const replacement = phrase[targetIndex];
    if (!replacement) continue;
    const pattern = new RegExp(`\\b${escapeRegExp(phrase[0])}\\b`, "gi");
    output = output.replace(pattern, replacement);
  }
  return output;
}

export function normalizeAdminLocale(value: unknown): AdminLocale {
  const locale = String(value || "").trim().toLowerCase();
  if (locale === "zh" || locale === "zh-cn" || locale === "zh_hans" || locale === "zh-hans") return "zh-CN";
  if (locale === "my" || locale === "my-mm" || locale === "my_mm" || locale === "mm") return "my-MM";
  return "en";
}

export function legacyStorageLocale(locale: AdminLocale) {
  return locale === "zh-CN" ? "zh" : locale === "my-MM" ? "my" : "en";
}

export function translateAdminText(input: string, locale: AdminLocale, aggressive = false) {
  if (locale === "en" || !input) return input;
  const exact = EXACT[locale].get(input);
  if (exact) return exact;

  const trimmed = input.trim();
  const exactTrimmed = EXACT[locale].get(trimmed);
  if (exactTrimmed) return input.replace(trimmed, exactTrimmed);

  const records = trimmed.match(/^(\d+)\s+records?$/i);
  if (records) return locale === "zh-CN" ? `${records[1]} 条记录` : `မှတ်တမ်း ${records[1]} ခု`;
  const logs = trimmed.match(/^(\d+)\s+log\(s\)$/i);
  if (logs) return locale === "zh-CN" ? `${logs[1]} 条日志` : `Log ${logs[1]} ခု`;
  const images = trimmed.match(/^(\d+)\s+image\(s\)$/i);
  if (images) return locale === "zh-CN" ? `${images[1]} 张图片` : `ပုံ ${images[1]} ပုံ`;
  const page = trimmed.match(/^(\d+)\s*\/\s*page$/i);
  if (page) return locale === "zh-CN" ? `${page[1]} / 页` : `${page[1]} / စာမျက်နှာ`;
  const platform = trimmed.match(/^Platform:\s*(.+?)\s*·\s*(.+)$/i);
  if (platform) return locale === "zh-CN" ? `平台：${platform[1]} · ${applyTerms(platform[2], locale)}` : `ပလက်ဖောင်း: ${platform[1]} · ${applyTerms(platform[2], locale)}`;

  if (!aggressive) return input;
  if (/^(https?:\/\/|www\.|[\w.+-]+@[\w.-]+\.)/i.test(trimmed)) return input;
  if (/^[A-Z0-9_.\-/]{2,}$/.test(trimmed)) return input;
  return input.replace(trimmed, applyTerms(trimmed, locale));
}
